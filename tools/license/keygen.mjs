#!/usr/bin/env node
/**
 * Generates YOUR production licence-signing key pair.
 *
 *   npm run license:keygen -- --out ~/tablewise-vendor/license-private.pem
 *
 * - Writes the PRIVATE key to --out (keep it offline / in a password manager / HSM;
 *   anyone with it can mint licences). Never commit it.
 * - Rewrites apps/api/src/lib/license-public-key.ts with the PUBLIC key and IS_DEV_KEY = false.
 *   Commit that file; every build after this verifies licences against your key.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const outArg = args[args.indexOf('--out') + 1];
if (!args.includes('--out') || !outArg) {
  console.error('Usage: npm run license:keygen -- --out <path-to-private-key.pem>');
  process.exit(1);
}
const out = path.resolve(outArg.replace(/^~/, os.homedir()));
if (fs.existsSync(out) && !args.includes('--force')) {
  console.error(`${out} already exists. Refusing to overwrite (pass --force if you really mean it).`);
  process.exit(1);
}

const { publicKey, privateKey } = crypto.generateKeyPairSync('ed25519');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const target = path.join(root, 'apps/api/src/lib/license-public-key.ts');
const pub = publicKey.export({ type: 'spki', format: 'pem' }).toString().trim();
fs.writeFileSync(target, `/**
 * Public half of the vendor licence-signing key. Generated by \`npm run license:keygen\`
 * on ${new Date().toISOString().slice(0, 10)}. The private key is held by the vendor and is not in this repository.
 */
export const IS_DEV_KEY = false;
export const LICENSE_PUBLIC_KEY_PEM = \`${pub}\`;
`);
console.log(`Private key written to ${out}  (KEEP THIS SAFE — back it up offline)`);
console.log(`Public key written to ${path.relative(root, target)} — commit this file.`);
console.log('Note: licences issued with the old key stop validating in builds made after this change.');
